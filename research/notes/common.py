"""Shared pieces for the page generators: paths, the open tensions, table helpers, and checks.

The generators write GitHub Markdown into docs/research/. Most numbers come from a file in
derived/ (or raw/manifest.json); the prose around the numbers is fixed in the scripts. The few
typed into the scripts instead, CMS_ROWS below among them, are listed in research/README.md with
where each comes from.
"""
import re
import sys
from pathlib import Path

RESEARCH = Path(__file__).resolve().parents[1]
DERIVED, RAW = RESEARCH / "derived", RESEARCH / "raw"
PAGES = RESEARCH.parent / "docs" / "research"
CODE = "../../research"  # the research folder, relative to a page in docs/research/
CMS_ROWS = 133_920  # rows in raw/MDS_Frequency_Q3_2026.csv, counted Oct 25, 2026; the file is downloaded, not committed

# The study read every source against five open tensions in Nametags' design. The derived files
# refer to them by number ("open tension 1").
TENSIONS = [
    ("Truthful naming versus care practice",
     "Nametags names people truthfully, while care staff often go along with a resident who takes one person for "
     "another."),
    ("Nova and AI disclosure",
     "Nova is told never to mention being an AI unless asked, which the research on deception, AI companions and "
     "disclosure to people with dementia has to be weighed against."),
    ("A camera and microphone in shared spaces",
     "The glasses see and hear other residents, staff and visitors, so bystander privacy and consent come into play."),
    ("Recognition failures that matter in care homes",
     "Masks, long separations, changes in appearance, staff turnover and look-alike relatives."),
    ("Where photos and audio are processed",
     "On a laptop the API runs locally; deployed to a server with [DEPLOY.md](../../DEPLOY.md), photos and audio leave "
     "the wearer's own machine."),
]

# The derived files were written against a one-page summary of Nametags (product.md) that is not in
# this repository. These rewrite its mentions for the pages; the derived files keep their wording.
REWRITES = [
    ("nothing in product.md shows whether", "nothing yet shows whether"),
    (" (open tension 1 in product.md)", " (open tension 1)"),
    ("the open tensions in product.md", "the study's open tensions"),
    ("that product.md describes", "that Nametags uses"),
    ("product.md gives Nova", "Nametags gives Nova"),
    ("Tension 5 and 'what leaves the device'", "Open tension 5, and what data leaves the device"),
    # The close reading puts a few of its sources' terms in single quotes. They aren't in the
    # verified pool, so the pages set them in italics instead.
    ("'early SD and AD'", "*early SD and AD*"),
    ("'CE'", "*CE*"),
    ("'phantom boarder'", "*phantom boarder*"),
    ("'mirror image'", "*mirror image*"),
    ("'TV sign'", "*TV sign*"),
]


def repo_text(text) -> str:
    text = str(text or "")
    for old, new in REWRITES:
        text = text.replace(old, new)
    assert "product.md" not in text, text
    return text


def cell(value) -> str:
    """One table cell: no pipes or line breaks."""
    return repo_text(value).replace("|", "/").replace("\n", " ")


def table(header, rows) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def short(title: str, n: int = 90) -> str:
    """A title cut at a word boundary, with an ellipsis when it is cut."""
    title = " ".join(str(title).split())
    return title if len(title) <= n else title[:n].rsplit(" ", 1)[0].rstrip(",:;.-") + "…"


def tensions_list() -> str:
    return "\n".join(f"{i}. **{name}.** {text}" for i, (name, text) in enumerate(TENSIONS, 1))


def generated_by(script: str) -> str:
    return (f"> [!NOTE]\n> Generated by [`research/{script}`]({CODE}/{script}) from the files in "
            f"[`research/derived/`]({CODE}/derived/). Edit the script, not this page.")


def write(name: str, text: str) -> Path:
    """Check a page's form (plain GitHub Markdown, no local paths), then write it to docs/research/
    (or the folder given as the first argument)."""
    assert not text.startswith("---"), f"{name}: frontmatter"
    for bad in ("[[", "![[", "> [!abstract]", "~/", "/Users/", "product.md"):
        assert bad not in text, f"{name}: {bad!r}"
    # A wrapped line that starts with "6. " would turn into a list item; the pages' own lists start "1. **".
    stray = re.search(r"^\d+\. (?!\*\*).*", text, re.M)
    assert not stray, f"{name}: a line starts like a list item: {stray.group(0)[:60]!r}"
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else PAGES
    out.mkdir(parents=True, exist_ok=True)
    path = out / name
    path.write_text(text.rstrip("\n") + "\n")
    return path
